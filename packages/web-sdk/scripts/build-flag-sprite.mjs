// Builds the flag sprite for `@telixon/web-sdk/flags`.
//
// One 4:3 cell per REGION_CODES entry, in engine order, plus a neutral cell at the end. The 2x sheet
// is rendered from the flag-icons artwork and halved for 1x. Each flag sits two pixels inside its
// cell, which keeps a neighboring flag out of the cell when the sheet is resampled.
//
// Usage: `pnpm run build:flags` from packages/web-sdk. Rerun after an engine update changes REGION_CODES.

import { REGION_CODES } from '@telixon/core';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const require = createRequire(import.meta.url);
const flagIcons = require('flag-icons/package.json');
const flagIconsDir = join(dirname(require.resolve('flag-icons/package.json')), 'flags/4x3');

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = join(packageDir, 'src/flags/assets');
const generatedDir = join(packageDir, 'src/flags/generated');

// Grid geometry at 2x. Each flag is drawn two pixels in from the top-left corner of its cell. The rest
// of the cell stays transparent.
const COLUMNS = 16;
const CELL_WIDTH = 64;
const CELL_HEIGHT = 48;
const FLAG_WIDTH = 60;
const FLAG_HEIGHT = 45;
const FLAG_INSET = 2;

// flag-icons files Ascension Island and Tristan da Cunha under Saint Helena's code.
const FILE_NAMES = { AC: 'sh-ac', TA: 'sh-ta' };

// A muted field with a globe outline, shown for an unresolved region.
const NEUTRAL_SVG = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 480">
  <rect width="640" height="480" fill="#d5d9df"/>
  <g fill="none" stroke="#7b838e" stroke-width="26" stroke-linecap="round">
    <circle cx="320" cy="240" r="140"/>
    <ellipse cx="320" cy="240" rx="62" ry="140"/>
    <path d="M180 240h280M206 172h228M206 308h228"/>
  </g>
</svg>`;

function flagSource(region) {
  if (region === null) return Buffer.from(NEUTRAL_SVG);
  return readFile(join(flagIconsDir, `${FILE_NAMES[region] ?? region.toLowerCase()}.svg`));
}

async function renderCell(region, index) {
  const input = await sharp(await flagSource(region), { density: 300 })
    .resize(FLAG_WIDTH, FLAG_HEIGHT, { fit: 'fill' })
    .png()
    .toBuffer();

  return {
    input,
    left: (index % COLUMNS) * CELL_WIDTH + FLAG_INSET,
    top: Math.floor(index / COLUMNS) * CELL_HEIGHT + FLAG_INSET,
  };
}

function stylesheet(rows) {
  return `/* Generated by scripts/build-flag-sprite.mjs. Do not edit. */

.tlx-flag {
  display: inline-block;
  flex-shrink: 0;
  width: 1.5em;
  aspect-ratio: 4 / 3;
  overflow: hidden;
  vertical-align: middle;
}

.tlx-flag__image {
  display: block;
  width: ${COLUMNS * 100}%;
  height: ${rows * 100}%;
  background-image: url(./sprite.png);
  background-repeat: no-repeat;
  background-size: 100% 100%;
  pointer-events: none;
  user-select: none;
  -webkit-print-color-adjust: exact;
  print-color-adjust: exact;
}

@media (min-resolution: 1.5dppx) {
  .tlx-flag__image {
    background-image: url(./sprite@2x.png);
  }
}
`;
}

function layoutModule(rows, regions) {
  return `// Generated by scripts/build-flag-sprite.mjs from @telixon/core REGION_CODES and flag-icons ${flagIcons.version}. Do not edit.
import type { RegionCode } from '@telixon/core';

export const SPRITE_COLUMNS: number = ${COLUMNS};
export const SPRITE_ROWS: number = ${rows};
export const SPRITE_CELL_WIDTH: number = ${CELL_WIDTH};
export const SPRITE_CELL_HEIGHT: number = ${CELL_HEIGHT};

// Cell order of the sheet; the neutral cell follows the last region.
export const SPRITE_REGIONS: readonly RegionCode[] = [
${regions.map((region) => `  '${region}',`).join('\n')}
];
`;
}

async function main() {
  const regions = [...REGION_CODES];
  const cells = [...regions, null];
  const rows = Math.ceil(cells.length / COLUMNS);
  const width = COLUMNS * CELL_WIDTH;
  const height = rows * CELL_HEIGHT;

  const layers = [];
  for (const [index, region] of cells.entries()) layers.push(await renderCell(region, index));

  const sheet = await sharp({ create: { width, height, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite(layers)
    .png()
    .toBuffer();

  // PNG beats both lossless and lossy WebP on this flat-color artwork.
  const png = { compressionLevel: 9, effort: 10 };
  const sprite2x = await sharp(sheet).png(png).toBuffer();
  const sprite1x = await sharp(sheet)
    .resize(width / 2, height / 2, { kernel: 'lanczos3' })
    .png(png)
    .toBuffer();

  await mkdir(assetsDir, { recursive: true });
  await mkdir(generatedDir, { recursive: true });

  const stylesheetPath = join(assetsDir, 'flags.css');
  const layoutPath = join(generatedDir, 'sprite-layout.ts');

  await writeFile(join(assetsDir, 'sprite@2x.png'), sprite2x);
  await writeFile(join(assetsDir, 'sprite.png'), sprite1x);
  await writeFile(stylesheetPath, stylesheet(rows));
  await writeFile(layoutPath, layoutModule(rows, regions));
  execFileSync('pnpm', ['exec', 'prettier', '--write', stylesheetPath, layoutPath], { stdio: 'inherit' });

  console.log(
    `${cells.length} cells in a ${COLUMNS}x${rows} grid: ` +
      `2x ${width}x${height} ${sprite2x.length} B, 1x ${width / 2}x${height / 2} ${sprite1x.length} B`,
  );
}

await main();
